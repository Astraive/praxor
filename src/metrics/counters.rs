use serde::{Deserialize, Serialize};
use std::sync::atomic::{AtomicU64, Ordering};

#[derive(Debug, Default)]
pub struct EngineMetrics {
    pub writes: AtomicU64,
    pub reads: AtomicU64,
    pub deletes: AtomicU64,
    pub wal_records: AtomicU64,
    /// Requests admitted to the core commit path (not WAL rotation/header syncs).
    pub write_admissions: AtomicU64,
    pub commit_groups: AtomicU64,
    pub commit_batches: AtomicU64,
    pub commit_syncs: AtomicU64,
    pub commit_sync_attempts: AtomicU64,
    pub commit_queue_wait_ns: AtomicU64,
    pub commit_sync_ns: AtomicU64,
    pub wal_bytes: AtomicU64,
    pub write_bytes: AtomicU64,
    pub read_errors: AtomicU64,
    pub write_errors: AtomicU64,
    pub segment_flushes: AtomicU64,
    pub automatic_flushes: AtomicU64,
    pub memtable_bytes: AtomicU64,
    pub write_stalls: AtomicU64,
    pub l0_pressure_compactions: AtomicU64,
    pub cache_hits: AtomicU64,
    pub cache_misses: AtomicU64,
    pub cache_admission_rejects: AtomicU64,
    pub bloom_negative_hits: AtomicU64,
    pub recovered_records: AtomicU64,
    pub checkpoints: AtomicU64,
    pub garbage_collections: AtomicU64,
    pub gc_files_reclaimed: AtomicU64,
    pub gc_bytes_reclaimed: AtomicU64,
}

#[derive(Clone, Debug, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct EngineMetricsSnapshot {
    pub writes: u64,
    pub reads: u64,
    pub deletes: u64,
    pub wal_records: u64,
    pub write_admissions: u64,
    pub commit_groups: u64,
    pub commit_batches: u64,
    pub commit_syncs: u64,
    pub commit_sync_attempts: u64,
    pub commit_queue_wait_ns: u64,
    pub commit_sync_ns: u64,
    pub wal_bytes: u64,
    pub write_bytes: u64,
    pub read_errors: u64,
    pub write_errors: u64,
    pub segment_flushes: u64,
    pub automatic_flushes: u64,
    pub memtable_bytes: u64,
    pub write_stalls: u64,
    pub l0_pressure_compactions: u64,
    pub cache_hits: u64,
    pub cache_misses: u64,
    pub cache_admission_rejects: u64,
    pub bloom_negative_hits: u64,
    pub recovered_records: u64,
    pub checkpoints: u64,
    pub garbage_collections: u64,
    pub gc_files_reclaimed: u64,
    pub gc_bytes_reclaimed: u64,
}

impl EngineMetrics {
    pub fn snapshot(&self) -> EngineMetricsSnapshot {
        EngineMetricsSnapshot {
            writes: self.writes.load(Ordering::Relaxed),
            reads: self.reads.load(Ordering::Relaxed),
            deletes: self.deletes.load(Ordering::Relaxed),
            wal_records: self.wal_records.load(Ordering::Relaxed),
            write_admissions: self.write_admissions.load(Ordering::Relaxed),
            commit_groups: self.commit_groups.load(Ordering::Relaxed),
            commit_batches: self.commit_batches.load(Ordering::Relaxed),
            commit_syncs: self.commit_syncs.load(Ordering::Relaxed),
            commit_sync_attempts: self.commit_sync_attempts.load(Ordering::Relaxed),
            commit_queue_wait_ns: self.commit_queue_wait_ns.load(Ordering::Relaxed),
            commit_sync_ns: self.commit_sync_ns.load(Ordering::Relaxed),
            wal_bytes: self.wal_bytes.load(Ordering::Relaxed),
            write_bytes: self.write_bytes.load(Ordering::Relaxed),
            read_errors: self.read_errors.load(Ordering::Relaxed),
            write_errors: self.write_errors.load(Ordering::Relaxed),
            segment_flushes: self.segment_flushes.load(Ordering::Relaxed),
            automatic_flushes: self.automatic_flushes.load(Ordering::Relaxed),
            memtable_bytes: self.memtable_bytes.load(Ordering::Relaxed),
            write_stalls: self.write_stalls.load(Ordering::Relaxed),
            l0_pressure_compactions: self.l0_pressure_compactions.load(Ordering::Relaxed),
            cache_hits: self.cache_hits.load(Ordering::Relaxed),
            cache_misses: self.cache_misses.load(Ordering::Relaxed),
            cache_admission_rejects: self.cache_admission_rejects.load(Ordering::Relaxed),
            bloom_negative_hits: self.bloom_negative_hits.load(Ordering::Relaxed),
            recovered_records: self.recovered_records.load(Ordering::Relaxed),
            checkpoints: self.checkpoints.load(Ordering::Relaxed),
            garbage_collections: self.garbage_collections.load(Ordering::Relaxed),
            gc_files_reclaimed: self.gc_files_reclaimed.load(Ordering::Relaxed),
            gc_bytes_reclaimed: self.gc_bytes_reclaimed.load(Ordering::Relaxed),
        }
    }
}
